// Generates generated/validators.js: standalone validator functions for everything the
// engine reads at runtime. They are plain code compiled from the schemas, so the browser
// never needs eval or new Function (which the platform's content security policy forbids).
//   node scripts/build-validators.mjs          write the file
//   node scripts/build-validators.mjs --check  fail if the file is out of date
import fs from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { schemas, schemaIds, dataSchemaFor } from '../src/index.js';

const OUT = new URL('../generated/validators.js', import.meta.url);

const ajv = new Ajv2020({ strict: true, strictRequired: false, allErrors: false, code: { source: true, esm: true, lines: false } });
// Documentation keywords stay in the source schemas; the browser does not need them.
// Maps whose keys are names (not keywords) are walked without dropping any key.
const NAME_MAPS = new Set(['properties', '$defs', 'patternProperties', 'dependentSchemas']);
const DOCS = new Set(['description', 'title', '$comment']);
function strip(node) {
  if (Array.isArray(node)) return node.map(strip);
  if (!node || typeof node !== 'object') return node;
  return Object.fromEntries(
    Object.entries(node)
      .filter(([key]) => !DOCS.has(key))
      .map(([key, value]) => [
        key,
        NAME_MAPS.has(key) && value && typeof value === 'object'
          ? Object.fromEntries(Object.entries(value).map(([k, v]) => [k, strip(v)]))
          : strip(value),
      ]),
  );
}
for (const schema of schemas) ajv.addSchema(strip(schema));

const exports = {
  validateSite: schemaIds.bundle.site,
  validateManifest: schemaIds.bundle.manifest,
  validatePage: schemaIds.bundle.page,
  validateSearch: schemaIds.bundle.search,
  validateLegacy: schemaIds.bundle.legacy,
  validateQuizData: dataSchemaFor('quiz'),
  validatePracticeData: dataSchemaFor('practice'),
  validateFlashcardsData: dataSchemaFor('flashcards'),
  validateFlowMapData: dataSchemaFor('flow-map'),
  validateLegacyWidgetData: dataSchemaFor('legacy-widget'),
};
// Ajv emits CommonJS require() for its runtime helpers even in ESM mode; turn them into imports.
const helpers = new Map();
const body = standaloneCode(ajv, exports).replace(/require\("(ajv\/dist\/runtime\/[a-z0-9]+)"\)\.default/g, (_, module) => {
  if (!helpers.has(module)) helpers.set(module, `runtime${helpers.size}`);
  return helpers.get(module);
});
if (/require\(/.test(body)) throw new Error('unexpected require() in generated validators');
// CommonJS interop differs between Node (module.exports) and bundlers (default export): accept both.
const imports = [...helpers]
  .map(([module, name]) => `import ${name}Module from '${module}.js';\nconst ${name} = ${name}Module.default ?? ${name}Module;`)
  .join('\n');
const code = `// Generated by packages/schema/scripts/build-validators.mjs. Do not edit.\n/* eslint-disable */\n${imports}\n${body.replace(/^"use strict";/, '')}`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== code) {
    console.error('packages/schema/generated/validators.js is out of date: run npm run schema:validators');
    process.exit(1);
  }
  console.log('Runtime validators are up to date.');
} else {
  fs.writeFileSync(OUT, code);
  console.log(`Wrote ${Object.keys(exports).length} validators (${Math.round(code.length / 1024)} KB).`);
}
